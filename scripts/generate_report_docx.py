#!/usr/bin/env python3
"""Генерация отчёта по ЛР2 в формате DOCX (структура по примеру курса). Запуск из корня репозитория."""
from __future__ import annotations

import sys
from pathlib import Path

try:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml.ns import qn
    from docx.shared import Cm, Pt
except ImportError:
    print("Установите: pip install python-docx", file=sys.stderr)
    sys.exit(1)


def set_doc_fonts(document: Document) -> None:
    normal = document.styles["Normal"]
    normal.font.name = "Times New Roman"
    normal.font.size = Pt(14)
    normal._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def add_heading(doc: Document, text: str, level: int = 1) -> None:
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.name = "Times New Roman"
        run.font.size = Pt(14 if level > 0 else 16)
        run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def add_para(doc: Document, text: str, bold: bool = False) -> None:
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = bold
    r.font.name = "Times New Roman"
    r.font.size = Pt(14)
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")


def add_code_block(doc: Document, lines: str) -> None:
    p = doc.add_paragraph()
    r = p.add_run(lines.strip("\n"))
    r.font.name = "Courier New"
    r.font.size = Pt(11)


